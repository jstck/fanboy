"""PlatformIO pre-build script: gzip web/*.html into src/web_pages.h.

Each page is served straight from flash with Content-Encoding: gzip, so there
is no separate filesystem image to upload. web/<name>.html becomes
WEB_<NAME>_GZ / WEB_<NAME>_GZ_LEN.
"""

import glob
import gzip
import os

Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

project_dir = env["PROJECT_DIR"]  # noqa: F821
src_dir = os.path.join(project_dir, "web")
dst = os.path.join(project_dir, "src", "web_pages.h")


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 20]) + ",")
    body = "\n".join(lines)
    return (
        f"static const uint8_t {name}_GZ[] = {{\n{body}\n}};\n"
        f"static const size_t {name}_GZ_LEN = {len(data)};\n"
    )


def generate():
    parts = []
    sizes = []
    for path in sorted(glob.glob(os.path.join(src_dir, "*.html"))):
        stem = os.path.splitext(os.path.basename(path))[0]
        name = "WEB_" + "".join(c if c.isalnum() else "_" for c in stem).upper()
        with open(path, "rb") as f:
            data = gzip.compress(f.read(), compresslevel=9, mtime=0)
        parts.append(c_array(name, data))
        sizes.append(f"{stem} {len(data)} B")
    out = (
        "// Generated by scripts/embed_web.py from web/*.html. Do not edit.\n"
        "#pragma once\n"
        "#include <stddef.h>\n"
        "#include <stdint.h>\n\n" + "\n".join(parts)
    )
    old = None
    if os.path.exists(dst):
        with open(dst) as f:
            old = f.read()
    if out != old:  # only touch the file when it changes, to avoid needless rebuilds
        with open(dst, "w") as f:
            f.write(out)
        print(f"embed_web: wrote {dst} ({', '.join(sizes)} gzipped)")


generate()
