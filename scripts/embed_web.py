"""PlatformIO pre-build script: gzip web/index.html into src/web_index.h.

The page is served straight from flash with Content-Encoding: gzip, so there is
no separate filesystem image to upload.
"""

import gzip
import os

Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

project_dir = env["PROJECT_DIR"]  # noqa: F821
src = os.path.join(project_dir, "web", "index.html")
dst = os.path.join(project_dir, "src", "web_index.h")


def generate():
    with open(src, "rb") as f:
        data = gzip.compress(f.read(), compresslevel=9, mtime=0)
    lines = []
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 20]) + ",")
    body = "\n".join(lines)
    out = (
        "// Generated by scripts/embed_web.py from web/index.html. Do not edit.\n"
        "#pragma once\n"
        "#include <stddef.h>\n"
        "#include <stdint.h>\n\n"
        f"static const uint8_t WEB_INDEX_GZ[] = {{\n{body}\n}};\n"
        f"static const size_t WEB_INDEX_GZ_LEN = {len(data)};\n"
    )
    old = None
    if os.path.exists(dst):
        with open(dst) as f:
            old = f.read()
    if out != old:  # only touch the file when it changes, to avoid needless rebuilds
        with open(dst, "w") as f:
            f.write(out)
        print(f"embed_web: wrote {dst} ({len(data)} bytes gzipped)")


generate()
